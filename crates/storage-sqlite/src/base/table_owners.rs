//! The owning side of every table in the account database. A new table needs an
//! entry here; `boundary_tests` fails until the registry matches a freshly
//! migrated database.

/// Which side of the crate a table, file or method belongs to.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub(crate) enum Side {
    /// The connection and migration ledger both sides build on.
    Base,
    /// The engine's storage: the `StorageProvider` traits and OpenMLS values.
    Protocol,
    /// App storage, including the transport-specific tables in `app/transport/`.
    App,
}

